<?php

namespace Trendix\AdminBundle\Entity;

use Doctrine\ORM\Mapping as ORM;

/**
 * Municipios
 *
 * @ORM\Table(name="municipios", indexes={@ORM\Index(name="id", columns={"id"})})
 * @ORM\Entity
 */
